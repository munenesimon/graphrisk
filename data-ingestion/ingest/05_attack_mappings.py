MERGE_MITIGATES = """
    UNWIND $batch AS row
    MATCH (tech:Technique {technique_id: row.attack_id})
    MATCH (fc:FrameworkControl {control_reference: row.control_id})
    MERGE (tech)-[r:MITIGATES]->(fc)
    SET r.mapping_type = "mitigates", r.source = "CTID"
"""

def ingest():
    print("=" * 55)
    print("  DS-05: ATT&CK -> NIST 800-53 MITIGATES Edges")
    print("=" * 55)
    print(f"\n[1/3] Building batch from {len(MAPPINGS)} curated mappings...")
    batch = [{"attack_id": t, "control_id": c} for t, c in MAPPINGS]

    print("\n[2/3] Connecting to Neo4j...")
    db = Neo4jClient()

    print("\n[3/3] Creating MITIGATES relationships...")
    db.run_batch(MERGE_MITIGATES, batch, batch_size=200)

    result = db.run("MATCH ()-[r:MITIGATES]->() RETURN count(r) AS total")
    total  = result[0]["total"] if result else 0
    db.close()

    print("\n" + "=" * 55)
    print("  ATT&CK -> NIST 800-53 Mappings Complete")
    print("=" * 55)
    print(f"  Mappings processed : {len(batch)}")
    print(f"  MITIGATES edges    : {total}")
    print("\n  Verify in Neo4j Browser:")
    print("  MATCH ()-[r:MITIGATES]->() RETURN count(r) AS total")
    print("=" * 55)

if __name__ == "__main__": ingest()
